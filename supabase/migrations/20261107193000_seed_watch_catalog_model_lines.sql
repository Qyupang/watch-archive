-- Seed initial shared watch brand and model-line catalog.
-- This migration intentionally seeds model families only; reference-specific
-- numbers and specifications are added later only after source verification.

alter table public.watch_catalog_references
  alter column reference_number drop not null;

alter table public.watch_catalog_models
  add column if not exists verification_status text not null default 'unverified'
  check (verification_status in ('unverified', 'community', 'verified'));

alter table public.watches
  add column if not exists catalog_model_id uuid
  references public.watch_catalog_models(id) on delete set null;

create index if not exists watches_catalog_model_idx
  on public.watches (catalog_model_id);

drop index if exists public.watch_catalog_references_identity_idx;
create unique index if not exists watch_catalog_references_identity_idx
  on public.watch_catalog_references (model_id, lower(coalesce(reference_number, '')), lower(coalesce(variant_name, '')));

drop function if exists public.search_watch_catalog(text, integer);

create function public.search_watch_catalog(p_query text, p_limit integer default 20)
returns table (
  id uuid,
  model_id uuid,
  brand_name text,
  collection_name text,
  model_name text,
  reference_number text,
  variant_name text,
  dial_variant text,
  case_diameter_mm numeric,
  thickness_mm numeric,
  lug_to_lug_mm numeric,
  movement text,
  caliber text,
  case_material text,
  crystal text,
  production_start smallint,
  production_end smallint,
  image_url text,
  verification_status text
)
language sql
stable
security invoker
set search_path = public
as $$
  select
    r.id,
    m.id,
    b.name,
    m.collection_name,
    m.model_name,
    r.reference_number,
    r.variant_name,
    r.dial_variant,
    r.case_diameter_mm,
    r.thickness_mm,
    r.lug_to_lug_mm,
    r.movement,
    r.caliber,
    r.case_material,
    r.crystal,
    coalesce(r.production_start, m.production_start),
    coalesce(r.production_end, m.production_end),
    r.image_url,
    coalesce(r.verification_status, m.verification_status)
  from public.watch_catalog_models m
  join public.watch_catalog_brands b on b.id = m.brand_id
  left join public.watch_catalog_references r on r.model_id = m.id
  where nullif(trim(p_query), '') is not null
    and (
      b.name ilike '%' || trim(p_query) || '%'
      or m.model_name ilike '%' || trim(p_query) || '%'
      or coalesce(m.collection_name, '') ilike '%' || trim(p_query) || '%'
      or coalesce(r.reference_number, '') ilike '%' || trim(p_query) || '%'
      or coalesce(r.variant_name, '') ilike '%' || trim(p_query) || '%'
    )
  order by
    case when lower(coalesce(r.reference_number, '')) = lower(trim(p_query)) then 0
         when lower(m.model_name) = lower(trim(p_query)) then 1
         else 2 end,
    b.name, m.model_name, r.reference_number nulls first
  limit greatest(1, least(coalesce(p_limit, 20), 50));
$$;

revoke all on function public.search_watch_catalog(text, integer) from public, anon;
grant execute on function public.search_watch_catalog(text, integer) to authenticated;

